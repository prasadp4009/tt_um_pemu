// emu_tt_top.v -- Zybo top for TT-WRAPPER FPGA emulation (test.py on hardware).
//
// Wires the REAL Tiny Tapeout wrapper tt_um_pemu to a host-loader that
// replicates test/test.py bit-for-bit: autobaud sync, RD_STATUS in PROG,
// chunked LOAD_IMEM of the 71-word SPI image, byte-exact VERIFY readback,
// GO, HALT via firmware command, TRANSFER command, CS# pin capture on uio,
// RD_TXFIFO result check -- all at 50 MHz via the FPGA's 125 MHz reference.
//
// Clocking / VIO / ILA infrastructure follows fpga/emu_top.v. The ASIC RTL
// under src/ is untouched; the SRAM macros resolve to fpga/sram_emu.v BRAM
// models.
//
// FPGA-EMULATION-ONLY. Not for ASIC synthesis.
//
// SPDX-License-Identifier: Apache-2.0
`default_nettype none

module emu_tt_top (
    input wire clk125_p
);
    // ------------------------------------------------------------------
    // Clock input
    // ------------------------------------------------------------------
    wire clk125_raw;
    IBUF ibuf_125 (.I(clk125_p), .O(clk125_raw));

    // ------------------------------------------------------------------
    // MMCM: 125 MHz -> test clock at the frequency selected by
    // fpga/clk_config.vh (generated by build_tt.tcl from the FREQ argument).
    // ------------------------------------------------------------------
    `include "clk_config.vh"
    wire test_clk_m;
    wire clkfb_pre, clkfb;
    wire mmcm_locked;

    MMCME2_ADV #(
        .CLKIN1_PERIOD   (8.0),
        .CLKFBOUT_MULT_F (`CLKFBOUT_MULT_F),
        .DIVCLK_DIVIDE   (1),
        .CLKOUT0_DIVIDE_F(`CLKOUT0_DIVIDE_F),
        .COMPENSATION    ("ZHOLD"),
        .BANDWIDTH       ("OPTIMIZED")
    ) mmcm (
        .CLKIN1    (clk125_raw),
        .CLKIN2    (1'b0),
        .CLKINSEL  (1'b1),
        .CLKFBIN   (clkfb),
        .CLKFBOUT  (clkfb_pre),
        .CLKOUT0   (test_clk_m),
        .LOCKED    (mmcm_locked),
        .PWRDWN    (1'b0),
        .RST       (1'b0),
        .CLKOUT1   (), .CLKOUT2   (), .CLKOUT3   (), .CLKOUT4   (),
        .CLKOUT5   (), .CLKOUT6   (),
        .CLKFBOUTB (), .CLKFBSTOPPED(), .CLKINSTOPPED(),
        .DO(), .DRDY(), .PSDONE()
    );
    BUFG bufg_fb  (.I(clkfb_pre),  .O(clkfb));
    wire test_clk;
    BUFG bufg_test(.I(test_clk_m), .O(test_clk));
    wire clk125_b;
    BUFG bufg_125 (.I(clk125_raw), .O(clk125_b));

    // =====================================================================
    // VIO control (same names as emu_top.v for script reuse)
    // =====================================================================
    wire vio_start_test;
    wire vio_reset;
    wire vio_inject_fault;
    wire [31:0] vio_status;
    wire [31:0] vio_signature;
    wire [31:0] vio_heartbeats;

    vio_0 u_vio (
        .clk          (clk125_b),
        .probe_out0   (vio_start_test),
        .probe_out1   (vio_reset),
        .probe_out2   (vio_inject_fault),
        .probe_in0    (vio_status),
        .probe_in1    (vio_signature),
        .probe_in2    (vio_heartbeats)
    );

    // Debug VIO: TT observation registers
    wire [31:0] tt_dbg0;
    wire [31:0] tt_dbg1;
    wire [31:0] tt_dbg2;
    vio_dbg u_vio_dbg (
        .clk      (clk125_b),
        .probe_in0(tt_dbg0),
        .probe_in1(tt_dbg1),
        .probe_in2(tt_dbg2)
    );

    // =====================================================================
    // Reset / control synchronizers (copied from emu_top.v)
    // =====================================================================
    reg vio_start_s, vio_start_m;
    always @(posedge test_clk) begin
        vio_start_m <= vio_start_test;
        vio_start_s <= vio_start_m;
    end

    reg vio_reset_s, vio_reset_m;
    always @(posedge test_clk) begin
        vio_reset_m <= vio_reset;
        vio_reset_s <= vio_reset_m;
    end

    reg vio_fault_s, vio_fault_m;
    always @(posedge test_clk) begin
        vio_fault_m <= vio_inject_fault;
        vio_fault_s <= vio_fault_m;
    end

    wire loader_rst_n = ~vio_reset_s;

    // =====================================================================
    // TT wrapper DUT
    // =====================================================================
    wire [7:0] ui_in_w;
    wire [7:0] uo_out_w;
    wire [7:0] uio_in_w;
    wire [7:0] uio_out_w;
    wire [7:0] uio_oe_w;
    wire       ena_w;
    wire       rst_n_w;

    wire       hp_rx;
    wire       hp_tx;
    wire       phase_reset;

    assign ui_in_w[0] = hp_rx;
    assign ui_in_w[7:1] = 7'b0;
    assign hp_tx = uo_out_w[0];
    assign ena_w = 1'b1;
    assign rst_n_w = loader_rst_n & ~phase_reset;

    // TT pad loopback: undriven pins read as 0; driven pins self-read back
    // (the SPI firmware self-reads a driven pin).
    assign uio_in_w = uio_out_w & uio_oe_w;

    tt_um_pemu u_dut (
        .ui_in  (ui_in_w),
        .uo_out (uo_out_w),
        .uio_in (uio_in_w),
        .uio_out(uio_out_w),
        .uio_oe (uio_oe_w),
        .ena    (ena_w),
        .clk    (test_clk),
        .rst_n  (rst_n_w)
    );

    // =====================================================================
    // TT host loader (replicates test/test.py)
    // =====================================================================
    wire [15:0] milestones;
    wire [7:0]  fail_code;
    wire        tt_pass;
    wire        loader_done;
    wire [31:0] signature;
    wire [7:0]  loader_st;
    wire        tx_busy_w;
    wire        rx_valid_w;

    emu_tt_loader u_loader (
        .clk          (test_clk),
        .rst_n        (loader_rst_n),
        .hp_rx        (hp_rx),
        .hp_tx        (hp_tx),
        .uio_out      (uio_out_w),
        .uio_oe       (uio_oe_w),
        .phase_reset  (phase_reset),
        .start_test   (vio_start_s),
        .inject_fault (vio_fault_s),
        .milestones   (milestones),
        .fail_code    (fail_code),
        .tt_pass      (tt_pass),
        .done         (loader_done),
        .signature    (signature),
        .st           (loader_st),
        .tx_busy_o    (tx_busy_w),
        .rx_valid_o   (rx_valid_w),
        .dbg0         (tt_dbg0),
        .dbg1         (tt_dbg1),
        .dbg2         (tt_dbg2)
    );

    // =====================================================================
    // Status CDC (copied from emu_top.v)
    // =====================================================================
    reg [31:0] status_tc;
    reg [31:0] signature_tc;
    reg [31:0] heartbeats_tc;
    reg [7:0]  reset_hold;

    always @(posedge test_clk) begin
        status_tc <= {tt_pass, 1'b0, 6'b0, fail_code, milestones};
        signature_tc <= signature;
        if (!loader_rst_n) begin
            reset_hold <= 8'd0;
        end else if (!vio_start_s) begin
            reset_hold <= 8'd0;
        end else if (reset_hold != 8'hFF) begin
            reset_hold <= reset_hold + 8'd1;
        end
        heartbeats_tc <= heartbeats_tc + 32'd1;
    end

    reg [31:0] status_s1, status_s2;
    reg [31:0] sig_s1, sig_s2;
    reg [31:0] hb_s1, hb_s2;

    always @(posedge clk125_b) begin
        status_s1 <= status_tc; status_s2 <= status_s1;
        sig_s1    <= signature_tc; sig_s2 <= sig_s1;
        hb_s1     <= heartbeats_tc; hb_s2 <= hb_s1;
    end

    assign vio_status     = status_s2;
    assign vio_signature  = sig_s2;
    assign vio_heartbeats = hb_s2;

    // =====================================================================
    // ILA removed: debug-hub routing conflict with clk125_b in this design.
    // Wave observation via VIO (milestones, signature, dbg0/1/2).
    // =====================================================================

endmodule
`default_nettype wire
